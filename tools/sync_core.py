#!/usr/bin/env python3
"""Keeps core.js embedded in the sync script (tools/sync/Code.gs) identical to the app's core.js. Run from the repo root.

    python3 tools/sync_core.py          # same as --check
    python3 tools/sync_core.py --check  # fails when the copy in Code.gs differs from core.js (CI)
    python3 tools/sync_core.py --fix    # writes core.js into Code.gs (adds the block at the end the first time)

Why (Pierre, 2026-11-03: progress is recalculated from the whole answer log by the sheet itself): the sync script replays
each player's answers with the app's own progress engine (core.js replayProgress), so the engine must be the same file.
The script updates itself from GitHub by installing Code.gs alone (autoUpdate), so core.js is copied into it rather than
added as a second file. The copy sits between the BEGIN and END markers, unchanged, inside a function that gives it a
`module` of its own: core.js then exports to module.exports (as in Node) instead of adding its names to the script's
globals, where some (TRUST, PHOTO_W, MEM, PLAYER0) are Code.gs's own constants. Code.gs reaches it as CORE_.
"""
import argparse, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, 'core.js')
GS = os.path.join(ROOT, 'tools', 'sync', 'Code.gs')
HEAD = ("// The app's core.js (progress engine, replayProgress), embedded by tools/sync_core.py: Code.gs reaches it as CORE_.\n"
        "// Its own module object keeps its names out of this script's globals (TRUST, MEM... are Code.gs's own).\n"
        "const CORE_ = (function () { const module = {exports: {}};\n")
BEGIN = '// BEGIN core.js (generated by tools/sync_core.py, do not edit)\n'
END = '// END core.js\n'
TAIL = 'return module.exports; })();\n'


def block(core):
    return HEAD + BEGIN + core + ('' if core.endswith('\n') else '\n') + END + TAIL


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--fix', action='store_true')
    a = ap.parse_args()
    core = open(CORE, encoding='utf-8').read()
    gs = open(GS, encoding='utf-8').read()
    want = block(core)
    i = gs.find(HEAD + BEGIN)
    if i < 0:
        new = gs.rstrip('\n') + '\n\n' + want
    else:
        j = gs.find(END + TAIL, i)
        if j < 0:
            sys.exit('tools/sync/Code.gs: the END core.js marker is missing; run with --fix after removing the broken block')
        new = gs[:i] + want + gs[j + len(END + TAIL):]
    if new == gs:
        print('core.js in Code.gs: OK')
        return
    if a.fix:
        open(GS, 'w', encoding='utf-8').write(new)
        print('core.js copied into tools/sync/Code.gs: add its entry in tools/sync/changes/<branch>.md, never VERSION (rule D3)')
        return
    sys.exit('✗ tools/sync/Code.gs does not hold the current core.js: run python3 tools/sync_core.py --fix and add tools/sync/changes/<branch>.md (rule D3)')


if __name__ == '__main__':
    main()
