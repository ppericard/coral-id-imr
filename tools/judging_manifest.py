# Builds judging/manifest.json: every photo an outside judging agent (e.g. Codex) must look at, with where it stands
# today (genus, view, source, candidate or live) and what Pierre already decided (never to be re-judged), plus the
# reference text per genus (IMR lecture cues first, then Coral Finder criteria) and the allowed categories.
# Earlier guesses (forms.json, quality.json) are left out on purpose, so the judge looks at each photo afresh.
# Usage: python3 tools/judging_manifest.py   (from the repo root; re-run after curation.json or data.json change)
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda p: json.load(open(os.path.join(ROOT, p)))
d, c = J('data.json'), J('curation.json')
VIEWS = ['wide', 'medium', 'macro']
X = c.get('exclude', {})
FJ = J('forms.json')
GF, GUN = FJ.get('gf', {}), set(FJ.get('gunsure', []))
G = c.get('genera', {})

def source(p):
    if p.get('cf'): return 'book'
    if p.get('imr'): return 'imr'
    if p.get('own'): return 'pierre'
    return {'dauin': 'inat-dauin', 'ph': 'inat-philippines'}.get(p.get('loc'), 'inat-elsewhere')

photos = {}
def put(n, p, view, status, extra=False):
    f = p['f']
    if f in X or f in photos: return
    k = G.get(n, {})
    out = (k.get('out') or {}).get(f)
    genus = n
    if out and out != 'cmp' and out in d['gen']: genus = out
    elif out == 'cmp': status = 'comparison'
    if status == 'live': view = (k.get('move') or {}).get(f, view)
    if f in (k.get('hide') or []): status = 'hidden'
    mine = {}
    gf = c.get('gf', {}).get(f, '')
    if gf.replace('p', '').replace('n', ''): mine['form'] = gf.replace('p', '').replace('n', '')
    if 'p' in gf or 'n' in gf: mine['polyps'] = 'p' in gf
    if f in c.get('quality', {}): mine['quality'] = c['quality'][f]
    if out: mine['genus'] = out
    if status == 'hidden': mine['hidden'] = True
    if any(f in (L or []) for L in (k.get('feat') or {}).values()): mine['featured'] = True
    if k.get('cover') == f: mine['cover'] = True
    e = {'f': f, 'genus': genus, 'view': view, 'source': source(p), 'status': status,
         'image': p['src'].replace('/original.', '/large.') if p.get('r') else f'img/{f}.webp', 'thumb': p['src'].replace('/original.', '/medium.') if p.get('r') else f'img/{f}-s.webp'}
    if p.get('t') and p.get('t') != genus: e['inat_label'] = p['t']
    if p.get('imr'): e['slide'] = p.get('slide')
    if p.get('multi') or extra: e['multi'] = True
    if p.get('cap'): e['caption'] = p['cap']
    if mine: e['pierre'] = mine
    # Growth form still to (re)guess: no IMR form guess yet, or a guess flagged for a second look (forms.json gunsure).
    if p.get('cf') is None and 'form' not in mine and (not GF.get(f, '').replace('p', '') or f in GUN): e['form_todo'] = True
    if not os.path.exists(os.path.join(ROOT, e['image'])): e['missing_image'] = True
    photos[f] = e

for n, g in d['gen'].items():
    two = g.get('levels') == 2
    for v in VIEWS:
        for p in (g.get('views') or {}).get(v, []): put(n, p, v, 'live')
        for p in (g.get('more') or {}).get(v, []): put(n, p, v, 'live', extra=True)
    for p in d.get('course', {}).get(n, []):
        put(n, p, 'macro' if p.get('v') == 'medium' and two else p.get('v'), 'live')
    add = G.get(n, {}).get('add') or {}
    for p in d.get('cand', {}).get(n, []):
        put(n, p, add.get(p['f']), 'live' if p['f'] in add else 'candidate')
    for p in g.get('book') or []:
        put(n, p, add.get(p['f'], p.get('view')), 'live' if p['f'] in add else 'candidate')

genera = {}
for n, g in d['gen'].items():
    genera[n] = {
        'slate_no': g.get('n'), 'starred': not g.get('n'), 'family': g.get('fam'),
        'views': ['wide', 'macro'] if g.get('levels') == 2 else VIEWS,
        'imr_cues': g.get('imr') or [], 'coral_finder': g.get('crit') or [], 'summary': g.get('sum'),
        'look_alikes': g.get('look') or [],
        'photos': sum(1 for p in photos.values() if p['genus'] == n),
    }

out = {
    'note': 'Generated by tools/judging_manifest.py. Input for judging/AGENTS.md. Do not edit by hand.',
    # IMR growth forms (IMR Lecture 6, slides 4-10), defined once in forms.json "forms".
    'forms': J('forms.json').get('forms', []),
    'views': {'wide': 'Colony', 'medium': 'Closer (10-30 cm)', 'macro': 'Corallites (Close-up for 2-view genera)'},
    'genera': genera,
    'photos': sorted(photos.values(), key=lambda e: (list(d['gen']).index(e['genus']), e['status'] != 'live', e['f'])),
}
os.makedirs(os.path.join(ROOT, 'judging'), exist_ok=True)
with open(os.path.join(ROOT, 'judging', 'manifest.json'), 'w') as fh:
    json.dump(out, fh, indent=1, ensure_ascii=False); fh.write('\n')
from collections import Counter
print(len(photos), 'photos', dict(Counter(p['status'] for p in photos.values())), dict(Counter(p['source'] for p in photos.values())))
