"""Settle a conflicted tools/sync/Code.gs only when every conflict is about metadata, keeping the branch's side.
Safe hunks: line 1 and `const VERSION = N;` (assignver.sh puts main's back with mainver.py) and anything inside the
embedded core.js block (sync_core.py --fix regenerates it). Any other conflict is the PR's own code against main's: the
file is left untouched and the exit status is 1 ("needs a hand"); main's whole file is never taken (it wiped #1285's code).
Usage: python3 -I resolve_gs.py PATH"""
import re
import sys

HEADER = re.compile(r'^// IMR Reef ID: progress sync.*VERSION \d+')
VERSION = re.compile(r'^const VERSION = \d+;\s*$')
BEGIN = '// BEGIN core.js (generated by tools/sync_core.py, do not edit)'
END = '// END core.js'


def resolve(text):
    """The text with every safe hunk settled to the branch's side, or None when a hunk is not safe."""
    out = []
    in_core = False
    lines = text.splitlines(keepends=True)
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.startswith('<<<<<<< '):
            s = line.rstrip('\r\n')
            if s == BEGIN:
                in_core = True
            elif s == END:
                in_core = False
            out.append(line)
            i += 1
            continue
        ours, theirs = [], []
        i += 1
        mid = False
        while i < len(lines) and not lines[i].startswith('>>>>>>> '):
            if lines[i].startswith('||||||| '):
                return None  # diff3 style: not what the queue sets up, left to a person
            if lines[i].startswith('======='):
                mid = True
            else:
                (theirs if mid else ours).append(lines[i])
            i += 1
        if i >= len(lines) or not mid:
            return None
        i += 1
        both = [l.rstrip('\r\n') for l in ours + theirs]
        meta = all(HEADER.match(l) or VERSION.match(l) for l in both)
        core = in_core and not any(l in (BEGIN, END) for l in both)
        if not (meta or core):
            return None
        out.extend(ours)
    return ''.join(out)


if __name__ == '__main__':
    path = sys.argv[1]
    new = resolve(open(path, encoding='utf-8', newline='').read())
    if new is None:
        print('%s: a conflict outside the version lines and the core.js block' % path)
        sys.exit(1)
    open(path, 'w', encoding='utf-8', newline='').write(new)
