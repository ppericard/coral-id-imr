// Rule S1 (docs/rules/subjects.md): every subject runs on one shared engine; a difference between subjects is declared
// and named in one place (a field of core.js SUBJECTS, a member of app.js UNITS, a flag listed in FLAGS below), never
// hidden in the shared code as a test on the subject. In the app's and the admin's files, outside the SUBJECTS list of
// core.js, and in the sync script's own code (tools/sync/Code.gs outside its copy of core.js): no subject id or name as a
// string literal ('coral', 'fish', 'Corals'...), no comparison of a subject's id with a literal, and no test of the subject
// by its place in SUBJECTS (SUBJ === SUBJECTS[k], S === CORE_.SUBJECTS.find(...)) but the lines listed in ALLOWED, each
// with its ROADMAP row. A SUBJECTS field true for exactly one subject (a feature switched on for that subject alone, such
// as replay) is a test on that subject wherever it is read: it is listed in FLAGS, with what it switches and its ROADMAP
// row; its reads, direct or through core.js replaySubject and replayedSubjects, are not listed line by line. UNITS
// members are each subject's own by design and are not checked here.
const test = require('node:test'),
  assert = require('node:assert'),
  fs = require('fs'),
  path = require('path'),
  block = require('./block.js');

const ROOT = path.join(__dirname, '..'),
  GS = 'tools/sync/Code.gs',
  FILES = [
    ...fs.readdirSync(ROOT).filter(f => f.endsWith('.js')),
    ...fs.readdirSync(path.join(ROOT, 'proto')).map(f => 'proto/' + f)
  ].filter(f => f.endsWith('.js')),
  read = f => fs.readFileSync(path.join(ROOT, f), 'utf8'),
  ROADMAP = read('docs/ROADMAP.md');
const core = read('core.js'),
  SUBJECTS = block(core, 'const SUBJECTS = [', '\n  ];', {through: true, file: 'core.js'}),
  ids = [...SUBJECTS.matchAll(/\bid: '([^']+)'/g)].map(m => m[1]),
  names = [...SUBJECTS.matchAll(/\bname: '([^']+)'/g)].map(m => m[1]),
  words = [...new Set([...ids, ...names, ...ids.map(s => s + 's')])];
// The sync script's own code: Code.gs without the copy of core.js tools/sync_core.py writes at its end (core.js is
// checked as itself above).
const ownGs = gs => {
  const i = gs.indexOf("// The app's core.js (progress engine, replayProgress), embedded by tools/sync_core.py"),
    b = gs.indexOf('// BEGIN core.js (generated by tools/sync_core.py, do not edit)\n'),
    e = gs.indexOf('// END core.js\n');
  assert.ok(i > 0 && b > i && e > b, `${GS}: the markers of its core.js copy are not where tools/sync_core.py writes them`);
  return gs.slice(0, i) + gs.slice(gs.indexOf('\n', e + 1) + 1);
};
const ONE_ENGINE = 'One engine for every subject, what is left';
// The hidden tests on a subject still in the code: [file, the line's text, the docs/ROADMAP.md row that removes it]. An
// entry whose line is gone fails (the exception went: drop it), and so does one whose ROADMAP row is gone (the row was
// done or dropped without the code): an exception never outlives its reason.
const ALLOWED = [
  // The first board subject (the corals) keeps its cache key and reads the "By genus" tab; the others their units.
  [GS, "const boardCache_ = S => S === CORE_.SUBJECTS.find(x => x.board) ? 'board14'", ONE_ENGINE],
  [GS, 'first = S === CORE_.SUBJECTS.find(x => x.board)', ONE_ENGINE]
];
// The SUBJECTS fields true for exactly one subject: [field, what it switches on, the docs/ROADMAP.md row that tracks it].
const FLAGS = [
  ['flat', "a flat subject: the corals' data.json, a flat list keyed by name, not a tree with ids (app.js build, GX)", ONE_ENGINE],
  [
    'replay',
    "the sheet's first replay path (Code.gs answerRows_, the reply's unprefixed replay, RVS) and the subject of an unlabelled row",
    ONE_ENGINE
  ],
  // One-engine step 2 split these out of replay, at its values (the audit's step 2; core.js SUBJECTS says each).
  ['hold', "the sheet's opening hold counts its answers (Code.gs hold_), adopted as this subject (sync.js holdAdopt)", ONE_ENGINE],
  ['offsets', "the sheet's photo memory and format offsets, fitted on its answers alone (Code.gs stats_; model.js pmem, pfmt)", ONE_ENGINE],
  [
    'anonBase',
    'signing in adds only what was played since its first answer signed out (ANONB: quiz.js answer, sync.js signIn)',
    ONE_ENGINE
  ],
  ['pulse', 'the one-tap question on how hard the game feels (quiz.js pulseDue)', ONE_ENGINE],
  ['sorry', 'the apology for its too-fast opening (progress.js sorryNotice)', ONE_ENGINE],
  ['recalcNote', 'the recalculation notes (progress.js RECALC), shown in this subject (recalcNotice)', ONE_ENGINE],
  ['achFeats', "the feats (runs, Sharp eye, corallites) kept by this subject's answers only (progress.js)", ONE_ENGINE]
];

// The checks, pure, so the planted cases below prove that each one bites.
const lit = new RegExp(`(['"\`])(${words.map(w => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})\\1`),
  idCmp = /\bSUBJ(?:\.id)?\s*[!=]==?\s*['"`]|['"`][^'"`]*['"`]\s*[!=]==?\s*SUBJ\.id\b|\bSUBJ\.id\s*[!=]==?\s*[A-Z_]+\.SUBJ\b/,
  place = /[!=]==?\s*(?:CORE_\.)?SUBJECTS(?:\[|\.find\()|\bSUBJECTS(?:\[[^\]]+\]|\.find\([^)]*\))\s*[!=]==?/;
function scan(f, src, allowed = ALLOWED) {
  const bad = [];
  src.split('\n').forEach((line, i) => {
    const at = `${f}:${i + 1}: ${line.trim()}`;
    if (allowed.some(([af, l]) => af === f && line.includes(l)) || /^\s*(\/\/|\/?\*)/.test(line)) return; // comment lines may name a subject
    if (lit.test(line)) bad.push('subject literal ' + at);
    if (idCmp.test(line)) bad.push('subject id compared ' + at);
    if (place.test(line)) bad.push('subject tested by its place ' + at);
  });
  return bad;
}
function exceptions(allowed, src, roadmap) {
  const bad = [];
  for (const [f, line, row] of allowed) {
    if (!src(f).includes(line)) bad.push(`stale exception, its line is gone from ${f}: drop it from ALLOWED (${line})`);
    if (!row || !roadmap.includes(row)) bad.push(`the exception in ${f} names no ROADMAP row, or one that is gone ("${row}")`);
  }
  return bad;
}
function flags(subjects, listed, roadmap) {
  const one = new Set([...new Set(subjects.flatMap(S => Object.keys(S)))].filter(k => subjects.filter(S => S[k] === true).length === 1)),
    bad = [];
  for (const k of one)
    if (!listed.some(([f]) => f === k)) bad.push(`SUBJECTS ${k} is true for one subject only: list it in FLAGS, with its ROADMAP row`);
  for (const [k, why, row] of listed) {
    if (!one.has(k)) bad.push(`stale flag, SUBJECTS ${k} is no longer true for exactly one subject: drop it from FLAGS`);
    if (!why || !row || !roadmap.includes(row)) bad.push(`the flag ${k} says not what it switches, or names no ROADMAP row ("${row}")`);
  }
  return bad;
}

test('rule S1: every exception still exists, with its ROADMAP row', () => {
  assert.deepStrictEqual(exceptions(ALLOWED, read, ROADMAP), []);
});

test('rule S1: the engine never names nor tests a subject, nor does the sync script', () => {
  assert.ok(ids.length >= 2 && ids.includes('coral'), JSON.stringify(ids));
  const gs = ownGs(read(GS));
  assert.ok(gs.split('\n').length > 3000 && gs.includes('function doGet('), `${GS}: its own code, read`);
  assert.ok(!gs.includes('const SUBJECTS = ['), `${GS}: without its copy of core.js`);
  const bad = [GS, ...FILES].flatMap(f => scan(f, f === GS ? gs : f === 'core.js' ? core.replace(SUBJECTS, '') : read(f)));
  assert.deepStrictEqual(bad, []);
});

test('rule S1: a SUBJECTS field true for one subject only is a listed flag, with its ROADMAP row', () => {
  const {SUBJECTS: S} = require('../core.js');
  assert.strictEqual(S.length, ids.length);
  assert.deepStrictEqual(flags(S, FLAGS, ROADMAP), []);
});

// One-engine step 2 (docs/reviews/2026-11-19-one-engine-audit.md §3): replay split into named fields at its own values, so
// nobody's progress moves (no rules version, rule D5). hold and offsets stay on replay's subject while the sheet computes
// them for it alone (Code.gs hold_ reads answerRows_, stats_ fits the photo memory on it); the app-only ones are on the
// subjects replay was on until the audit's later step that spreads each changes this test with it.
test('rule S1: the fields split out of replay keep its values (one-engine step 2)', () => {
  const {SUBJECTS: S, replaySubject} = require('../core.js'),
    on = k => S.filter(x => x[k] === true).map(x => x.id),
    rp = on('replay');
  assert.deepStrictEqual(rp, [replaySubject()]);
  for (const k of ['hold', 'offsets']) assert.deepStrictEqual(on(k), rp, `${k}: the sheet computes it for replay's subject only`);
  for (const k of ['anonBase', 'pulse', 'sorry', 'recalcNote']) assert.deepStrictEqual(on(k), rp, `${k}: at replay's values`);
  // the replay subject's pooled statistics are the plain ?stats=1 reply: no stats gate (model.js statsJoin, sync.js
  // loadOwnStats no longer ask replay)
  for (const x of S) if (x.replay) assert.ok(!x.stats, `${x.id}: replay's subject with a stats gate`);
  // the circle-3 threshold the tree subjects had in app.js, now each one's own (treeC3)
  for (const x of S)
    if (!x.flat) assert.deepStrictEqual(x.gate && x.gate.c3, {entries: 0.55, mean: 0.5}, `${x.id}: gate c3`);
    else assert.ok(!x.gate, `${x.id}: a flat subject has no circles`);
});

test('rule S1: the checks catch what they are for (planted cases)', () => {
  const [a, b] = ids;
  // a subject's name in the sync script's code, its id compared, a test by its place, the first board subject
  assert.strictEqual(scan(GS, `const t = sid === '${b}' ? 1 : 2;`).length, 1);
  assert.strictEqual(scan('x.js', `if (SUBJ.id === '${a}') go();`).length, 2, 'a literal and a comparison');
  assert.strictEqual(scan(GS, 'const first = S === CORE_.SUBJECTS.find(x => x.board);', []).length, 1);
  assert.strictEqual(scan('x.js', 'if (SUBJECTS[1] !== SUBJ) return;').length, 1);
  assert.strictEqual(scan('x.js', 'if (SUBJ.id === SUBJECTS[0].id) go();').length, 1);
  // what stays allowed: a comment, the default subject of an unlabelled row, a lookup by id
  assert.deepStrictEqual(scan(GS, `  // the ${a}' rows`), []);
  assert.deepStrictEqual(scan(GS, 'const subj = a => word_(a.s, W, 20) || CORE_.SUBJECTS[0].id;'), []);
  assert.deepStrictEqual(scan(GS, 'const S = CORE_.SUBJECTS.find(S => S.id === sid) || {};'), []);
  // a listed line only in its own file
  assert.strictEqual(scan('x.js', ALLOWED[1][1]).length, 1);
  // the flags: one undeclared, one stale, one with no ROADMAP row
  const subj = [{id: 'a', zz: true, flat: true}, {id: 'b'}, {id: 'c', zz: false}];
  assert.match(flags(subj, [['flat', 'why', ONE_ENGINE]], ROADMAP).join('\n'), /SUBJECTS zz is true for one subject only/);
  assert.match(
    flags(
      subj,
      [
        ['zz', 'why', ONE_ENGINE],
        ['flat', 'why', ONE_ENGINE],
        ['yy', 'why', ONE_ENGINE]
      ],
      ROADMAP
    ).join(),
    /stale flag, SUBJECTS yy/
  );
  assert.match(
    flags(
      subj,
      [
        ['zz', 'why', 'no such row'],
        ['flat', 'why', ONE_ENGINE]
      ],
      ROADMAP
    ).join(),
    /flag zz .* no ROADMAP row/
  );
  assert.deepStrictEqual(
    flags(
      subj,
      [
        ['zz', 'why', ONE_ENGINE],
        ['flat', 'why', ONE_ENGINE]
      ],
      ROADMAP
    ),
    []
  );
  // an exception: its line gone, its row gone or absent
  assert.match(exceptions([['progress.js', 'no such line', ONE_ENGINE]], read, ROADMAP).join(), /stale exception/);
  assert.match(exceptions([[ALLOWED[0][0], ALLOWED[0][1]]], read, ROADMAP).join(), /names no ROADMAP row/);
});
