test("trusted_root: main's code runs on the PR's data, and its writes land in the PR checkout", () => {
  tmp(d => {
    const g = (...a) => {
      const r = spawnSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@t', ...a], {cwd: d, encoding: 'utf8'});
      assert.strictEqual(r.status, 0, r.stderr);
      return r.stdout;
    };
    const w = (f, s) => {
      fs.mkdirSync(path.dirname(path.join(d, f)), {recursive: true});
      fs.writeFileSync(path.join(d, f), s);
    };
    g('init', '-q');
    const probe = who =>
      `import os\nROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))\nprint('${who}')\nprint(open(os.path.join(ROOT, 'tools', 'data.txt')).read())\nopen(os.path.join(ROOT, 'out.txt'), 'w').write('written by ${who}')\n`;
    w('tools/probe.py', probe('main'));
    w('tools/data.txt', 'main data');
    w('out.txt', 'old');
    w('.gitattributes', '/tools/ export-ignore\n'); // as in the repository: git archive would skip tools/
    g('add', '-A');
    g('commit', '-q', '-m', 'main');
    g('update-ref', 'refs/remotes/origin/main', 'HEAD');
    // the PR's side: its own probe.py (a hostile one), its data, a new top-level file
    w('tools/probe.py', probe('PR'));
    w('tools/data.txt', 'PR data');
    w('extra.txt', 'new');
    w('tools/sneaky.so', 'x'); // anything Python could import is never linked as data
    w('tools/sneaky.pyc', 'x');
    g('add', '-A');
    const script = path.join(d, 'run.sh');
    fs.writeFileSync(
      script,
      `. "${path.join(DIR, 'lib.sh')}"\ncd "${d}" || exit 1\nneed_trusted\npython3 -E "$T/tools/probe.py"\ncat "$T/extra.txt"\nls "$T/tools" | tr '\\n' ' '\n`
    );
    const r = spawnSync('bash', [script], {encoding: 'utf8', env: {...process.env, QUEUE_DIR: path.join(d, 'qd'), REPO_DIR: d}});
    assert.strictEqual(r.status, 0, r.stderr);
    assert.strictEqual(r.stdout, 'main\nPR data\nnewdata.txt probe.py ');
    assert.strictEqual(fs.readFileSync(path.join(d, 'out.txt'), 'utf8'), 'written by main');
    assert.deepStrictEqual(fs.readdirSync(path.join(d, 'qd')), [], 'the shadow root is removed on exit');
  });
});

