test('assignver: a Code.gs conflict in the PR code is "needs a hand", never main\'s whole file (P1)', () => {
  const t = read('assignver.sh');
  assert.match(
    t,
    /tools\/sync\/Code\.gs\) python3 -I "\$Q\/resolve_gs\.py" "\$f" >\/dev\/null \|\| \{[^}]*needs a hand[^}]*git merge --abort; exit 2/
  );
  assert.doesNotMatch(t, /Code\.gs[^\n]*--theirs/);
  tmp(d => {
    // version lines only (line 1, const VERSION): settled to the branch's side
    const meta = gs(
      d,
      conflict(HDR + '10 (x).\n', HDR + '11 (y).\n') + 'code();\n' + conflict('const VERSION = 10;\n', 'const VERSION = 11;\n')
    );
    assert.strictEqual(resolveGs(meta).status, 0);
    assert.strictEqual(fs.readFileSync(meta, 'utf8'), HDR + '10 (x).\ncode();\nconst VERSION = 10;\n');
    // the PR's own code against main's: refused, the file untouched
    const text = 'a();\n' + conflict('pr();\n', 'main();\n') + 'b();\n';
    const code = gs(d, text);
    const r = resolveGs(code);
    assert.strictEqual(r.status, 1);
    assert.match(r.stdout, /outside the version lines/);
    assert.strictEqual(fs.readFileSync(code, 'utf8'), text);
    // a version hunk next to a code hunk: still refused
    const mixed = gs(d, conflict('const VERSION = 10;\n', 'const VERSION = 11;\n') + conflict('pr();\n', 'main();\n'));
    assert.strictEqual(resolveGs(mixed).status, 1);
    // a conflict inside the core.js block is regenerated by sync_core --fix: settled; the same lines outside it are not
    const inCore = gs(d, BEGIN + conflict('var a = 1;\n', 'var a = 2;\n') + '// END core.js\n');
    assert.strictEqual(resolveGs(inCore).status, 0);
    assert.strictEqual(fs.readFileSync(inCore, 'utf8'), BEGIN + 'var a = 1;\n// END core.js\n');
    assert.strictEqual(resolveGs(gs(d, conflict('var a = 1;\n', 'var a = 2;\n'))).status, 1);
    // a hunk that takes in the block's end marker is not a metadata hunk
    assert.strictEqual(resolveGs(gs(d, BEGIN + conflict('x();\n// END core.js\n', 'y();\n// END core.js\n'))).status, 1);
  });
});

