// ---- the #1315 review findings (round 1) ----
const read = f => fs.readFileSync(path.join(DIR, f), 'utf8');
const tmp = fn => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'queue-test-'));
  try {
    return fn(d);
  } finally {
    fs.rmSync(d, {recursive: true, force: true});
  }
};
const HDR = '// IMR Reef ID: progress sync for the RAs, stored in this Google Sheet. VERSION ';
const BEGIN = '// BEGIN core.js (generated by tools/sync_core.py, do not edit)\n';
const conflict = (ours, theirs) => `<<<<<<< HEAD\n${ours}=======\n${theirs}>>>>>>> origin/main\n`;
const gs = (d, text) => {
  const f = path.join(d, 'Code.gs');
  fs.writeFileSync(f, text);
  return f;
};
const resolveGs = f => spawnSync('python3', ['-I', path.join(DIR, 'resolve_gs.py'), f], {encoding: 'utf8'});

test('assignver: a Code.gs conflict in the PR code is "needs a hand", never main\'s whole file (P1)', () => {
  const t = read('assignver.sh');
  assert.match(
    t,
    /tools\/sync\/Code\.gs\) python3 -I "\$Q\/resolve_gs\.py" "\$f" >\/dev\/null \|\| \{[^}]*needs a hand[^}]*git merge --abort; exit 2/
  );
  assert.doesNotMatch(t, /Code\.gs[^\n]*--theirs/);
  tmp(d => {
    // version lines only (line 1, const VERSION): settled to the branch's side
    const meta = gs(
      d,
      conflict(HDR + '10 (x).\n', HDR + '11 (y).\n') + 'code();\n' + conflict('const VERSION = 10;\n', 'const VERSION = 11;\n')
    );
    assert.strictEqual(resolveGs(meta).status, 0);
    assert.strictEqual(fs.readFileSync(meta, 'utf8'), HDR + '10 (x).\ncode();\nconst VERSION = 10;\n');
    // the PR's own code against main's: refused, the file untouched
    const text = 'a();\n' + conflict('pr();\n', 'main();\n') + 'b();\n';
    const code = gs(d, text);
    const r = resolveGs(code);
    assert.strictEqual(r.status, 1);
    assert.match(r.stdout, /outside the version lines/);
    assert.strictEqual(fs.readFileSync(code, 'utf8'), text);
    // a version hunk next to a code hunk: still refused
    const mixed = gs(d, conflict('const VERSION = 10;\n', 'const VERSION = 11;\n') + conflict('pr();\n', 'main();\n'));
    assert.strictEqual(resolveGs(mixed).status, 1);
    // a conflict inside the core.js block is regenerated by sync_core --fix: settled; the same lines outside it are not
    const inCore = gs(d, BEGIN + conflict('var a = 1;\n', 'var a = 2;\n') + '// END core.js\n');
    assert.strictEqual(resolveGs(inCore).status, 0);
    assert.strictEqual(fs.readFileSync(inCore, 'utf8'), BEGIN + 'var a = 1;\n// END core.js\n');
    assert.strictEqual(resolveGs(gs(d, conflict('var a = 1;\n', 'var a = 2;\n'))).status, 1);
    // a hunk that takes in the block's end marker is not a metadata hunk
    assert.strictEqual(resolveGs(gs(d, BEGIN + conflict('x();\n// END core.js\n', 'y();\n// END core.js\n'))).status, 1);
  });
});

test('headfind: a bot finding on the head with no reply and no resolved thread, or a security comment, counts (P1)', () => {
  const bot = {type: 'Bot', login: 'review-bot[bot]'},
    person = {type: 'User', login: 'someone'};
  const rv = [
    {id: 1, commit_id: 'H', user: bot, path: 'a.sh', line: 3}, // open finding on the head
    {id: 2, commit_id: 'H', user: bot, path: 'b.sh', line: 4}, // resolved thread
    {id: 3, commit_id: 'H', user: bot, path: 'c.sh', line: 5}, // answered
    {id: 4, commit_id: 'H', user: person, in_reply_to_id: 3},
    {id: 5, commit_id: 'OLD', user: bot, path: 'd.sh', line: 6}, // older head: not counted here
    {id: 6, commit_id: 'H', user: person, path: 'e.sh', line: 7} // a person's own comment
  ];
  const th = [
    {resolved: true, comment_ids: [2]},
    {resolved: false, comment_ids: [1]}
  ];
  const iss = [
    {id: 10, user: bot, body: "Codex Review: Didn't find any major issues (security ok)", created_at: '2026-11-20T10:00:00Z'},
    {id: 11, user: bot, body: 'A security alert: secret found', created_at: '2026-11-20T10:05:00Z'},
    {id: 12, user: bot, body: 'secret scanning alert, old head', created_at: '2026-11-20T08:00:00Z'},
    {
      id: 14,
      user: bot,
      body: '<!-- codex-pull-request-review-summary -->\n| Security Review | Completed |',
      created_at: '2026-11-20T10:06:00Z'
    }
  ];
  tmp(d => {
    const w = (n, pages) => {
      const f = path.join(d, n);
      fs.writeFileSync(f, pages.map(p => JSON.stringify(p)).join('\n')); // gh --paginate: one array per page
      return f;
    };
    const run = i =>
      spawnSync(
        'python3',
        [
          '-I',
          path.join(DIR, 'headfind.py'),
          'H',
          '2026-11-20T09:00:00Z',
          w('rv', [rv.slice(0, 3), rv.slice(3)]),
          w('th', [th]),
          w('iss', i)
        ],
        {encoding: 'utf8'}
      );
    let r = run([iss]);
    assert.strictEqual(r.status, 0, r.stderr);
    const lines = r.stdout.trim().split('\n');
    assert.strictEqual(lines[0], '2');
    assert.match(lines[1], /review comment 1 on a\.sh:3/);
    assert.match(lines[2], /security comment 11/);
    // a person's later comment answers the security comment
    r = run([iss, [{id: 13, user: person, body: 'not an issue: test-only', created_at: '2026-11-20T10:10:00Z'}]]);
    assert.strictEqual(r.stdout.trim().split('\n')[0], '1');
  });
});

test('nightq skips a PR with unanswered head findings and passes the queue repository to the train (P1, P2)', () => {
  const t = read('nightq.sh');
  assert.match(t, /\*"unanswered@head: 0 \|"\*\) ;; \*\) log "#\$n: SKIPPED \(findings or security comments on the head/);
  assert.match(t, /TRAIN_REPO="\$QUEUE_REPO_NAME" python3 tools\/train\.py/);
  assert.match(read('lib.sh'), /QUEUE_REPO_NAME=\$\{QUEUE_REPO:-ppericard\/coral-id-imr\}\nR=repos\/\$QUEUE_REPO_NAME/);
  const p = read('prstate.sh');
  assert.match(p, /gh api --paginate "\$R\/issues\/\$n\/comments\?per_page=100"/);
  assert.match(p, /gh api --paginate "\$R\/pulls\/\$n\/comments\?per_page=100"/);
  assert.match(p, /unanswered@head: \$\{un:-\?\}/);
  // fails closed: a page, the threads or the head's date that could not be read leaves "?", which nightq.sh skips
  assert.strictEqual((p.match(/\|\| ok=0/g) || []).length, 5);
  assert.match(p, /un="\?"\n\s*if \[ \$ok = 1 \]/);
});

