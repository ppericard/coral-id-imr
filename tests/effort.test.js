// --check
const figures = md => py(`print(json.dumps(effort.find_figures(${JSON.stringify(md)})))`);
const bad = md =>
  figures(md)
    .filter(f => !f[2])
    .map(f => f[1]);

test('--check finds every kind of effort figure', () => {
  assert.deepStrictEqual(bad('It takes 3 h.'), ['3 h']);
  assert.deepStrictEqual(bad('About 50-140 agent hours of work.'), ['50-140 agent hours']);
  assert.deepStrictEqual(bad('2 to 4 hours of agent time'), ['2 to 4 hours']);
  assert.deepStrictEqual(bad('One agent-day, maybe.'), ['agent-day']);
  assert.deepStrictEqual(bad('Roughly 3 days.'), ['3 days']);
  assert.deepStrictEqual(bad('Two weeks at most, so 2 weeks.').length, 1, 'a figure is reported once, not once per pattern');
  assert.deepStrictEqual(bad('Several days of work, a few weeks of waiting.'), ['Several days', 'a few weeks']);
  assert.deepStrictEqual(bad('Takes 30 min, or 20-40 minutes, or 20 to 40 mins.'), ['30 min', '20-40 minutes', '20 to 40 mins']);
  assert.deepStrictEqual(bad('The tool prints 3.0 d, or 2.5-4 d, or 1.5 d.'), ['3.0 d', '2.5-4 d', '1.5 d']);
  assert.deepStrictEqual(bad('1.5 h, then 0,5 hours'), ['1.5 h', '0,5 hours']);
});

test('--check is quiet on what is no effort figure', () => {
  assert.deepStrictEqual(bad('Opened at 17h30 on 2026-11-18, build 2h45 and a hash like a3h9.'), []);
  assert.deepStrictEqual(bad('The photos weigh 3 MB and the app has 40 genera.'), []);
  assert.deepStrictEqual(bad('He walks the dog.'), []);
});

test('--check accepts a figure with PR references on its line or its bullet', () => {
  assert.deepStrictEqual(bad('Median 3 h (comparable to #1042, #1050, #1061).'), []);
  assert.deepStrictEqual(bad('- The study: 2-4 agent hours\n  comparable to #812 and #833\n- Another one: 5 h'), ['5 h']);
  assert.deepStrictEqual(bad('- A bullet with 2 h\n\n  #12 after a blank line does not count'), ['2 h']);
  assert.deepStrictEqual(bad('| step | 2 h | #44 |\n| other | 3 h | |'), ['3 h']);
  assert.deepStrictEqual(bad('2 h on its own line\n#12 on the next line'), ['2 h']);
  assert.deepStrictEqual(bad('# 12 is a heading, not a PR: 2 h'), ['2 h']);
  assert.deepStrictEqual(bad('Entity &#123; is not a PR: 2 h'), ['2 h']);
});

test('--check skips code blocks and takes the effort-ok marker', () => {
  assert.deepStrictEqual(bad('```\nsleep 3 h\n```\n'), []);
  assert.deepStrictEqual(bad('Keep logs 30 days <!-- effort-ok: retention, not an estimate -->'), []);
  assert.deepStrictEqual(bad('Line 1\nKeep logs 30 days'), ['30 days']);
});

test('--check exit status and message, from a file', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'effort-'));
  const run = md => {
    const f = path.join(dir, 'study.md');
    fs.writeFileSync(f, md);
    return spawnSync('python3', ['-B', path.join(ROOT, 'tools/effort.py'), '--check', f], {encoding: 'utf8', cwd: ROOT, timeout: 20000});
  };
  const ok = run('Medium PRs took 40 min (#1, #2).\n- Study: 2 h, like #3\n');
  assert.strictEqual(ok.status, 0, ok.stdout + ok.stderr);
  const ko = run('Intro\n\nThe work is 50-140 agent hours.\n');
  assert.strictEqual(ko.status, 1);
  assert.match(ko.stdout, /study\.md:3: effort figure "50-140 agent hours" has no PR reference/);
  fs.rmSync(dir, {recursive: true});
});
