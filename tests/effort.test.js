require('./slot.js').testGuard();
// tools/effort.py: the type and size derivation, the record of one PR and the --check parser, on fixtures, no network.
const test = require('node:test'),
  assert = require('node:assert'),
  fs = require('fs'),
  os = require('os'),
  path = require('path'),
  {execFileSync, spawnSync} = require('child_process');
const ROOT = path.join(__dirname, '..');

// Runs `body` (Python, with `effort` imported, printing JSON) and returns the parsed result.
const py = body =>
  JSON.parse(
    execFileSync('python3', ['-B', '-c', 'import json,sys; sys.path.insert(0, "tools"); import effort\n' + body], {
      cwd: ROOT,
      timeout: 20000
    }).toString()
  );
const classify = (title, paths, labels = []) =>
  py(`print(json.dumps(effort.classify(${JSON.stringify(title)}, ${JSON.stringify(paths)}, ${JSON.stringify(labels)})))`);

test('type: study, docs, tooling, content, engine, sheet, admin, feature, fix', () => {
  assert.strictEqual(classify('Placement test check (study, docs only)', ['docs/reviews/2026-11-18-placement.md']), 'study');
  assert.strictEqual(classify('Rules: estimates', ['AGENTS.md', 'docs/rules/ship.md', 'docs/reviews/x.md']), 'docs');
  assert.strictEqual(classify('A new check', ['tools/foo.py', 'tests/foo.test.js']), 'tooling');
  assert.strictEqual(classify('Fish reference photos', ['fish-photos.json', 'img/a.webp', 'tools/fish_refs.py']), 'content');
  assert.strictEqual(classify('Mnemonics', ['data.json']), 'content');
  assert.strictEqual(classify('A new game format', ['quiz.js', 'app.js', 'tests/x.test.js']), 'engine');
  assert.strictEqual(classify('Typed answers', ['model.js']), 'engine');
  assert.strictEqual(classify('Sheet v101', ['tools/sync/Code.gs', 'docs/ARCHITECTURE.md']), 'sheet');
  assert.strictEqual(classify('Admin: screens', ['admin.js', 'admin.css', 'tests/admin.smoke.js']), 'admin');
  assert.strictEqual(classify('A feedback sheet', ['app.js', 'app.css', 'index.html']), 'feature');
});

test('type: a fix is told by the title or the label, and only where code changes', () => {
  assert.strictEqual(classify("Admin Players: a row's bar never runs past the table", ['admin.css']), 'fix');
  assert.strictEqual(classify('Fix the streak', ['quiz.js']), 'fix');
  assert.strictEqual(classify('Streak', ['quiz.js'], ['bug']), 'fix');
  assert.strictEqual(classify('Fix a typo in the rules', ['docs/rules/ship.md']), 'docs');
  assert.strictEqual(classify('Never ask after 17:30 (study)', ['docs/reviews/a.md']), 'study');
  assert.strictEqual(classify('Fix photo', ['img/a.webp']), 'content');
});

test('type: a Code.gs that only copies core.js is engine, one with its own changes is sheet', () => {
  const t = (paths, changes) => py(`print(json.dumps(effort.classify("Step", ${JSON.stringify(paths)}, [], ${JSON.stringify(changes)})))`);
  const paths = ['core.js', 'tools/sync/Code.gs'];
  assert.strictEqual(t(paths, {'core.js': 40, 'tools/sync/Code.gs': 44}), 'engine', 'a pure copy is core.js + 4 lines');
  assert.strictEqual(t(paths, {'core.js': 40, 'tools/sync/Code.gs': 140}), 'sheet');
  assert.strictEqual(t(['tools/sync/Code.gs'], {'tools/sync/Code.gs': 6}), 'sheet');
});

